// Bundles sample_docs/*.md into lib/sample-docs.generated.ts so auto-seeding works on serverless hosts
// where loose files are not shipped with the function. Runs automatically before dev and build.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "sample_docs");
const docs = fs.readdirSync(dir).filter((f) => /\.(md|txt)$/i.test(f)).sort()
  .map((f) => ({ name: f, text: fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n") }));
const out = `// AUTO-GENERATED by scripts/embed-samples.mjs from sample_docs/. Do not edit by hand.\nexport const SAMPLE_DOCS: { name: string; text: string }[] = ${JSON.stringify(docs, null, 2)};\n`;
fs.writeFileSync(path.join(root, "lib", "sample-docs.generated.ts"), out);
console.log(`embedded ${docs.length} sample docs`);
